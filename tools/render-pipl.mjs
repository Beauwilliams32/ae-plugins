#!/usr/bin/env node
// Render packaging/<Plugin>PiPL.r from specs/<Plugin>.json.
//
// The specs are produced by tools/recover.mjs, which reads the PiPL resource out
// of each surviving .plugin bundle. This tool goes the other way: it writes Rez
// source that rebuilds those same resources from scratch.
//
// That direction is what makes the recovery verifiable. A PiPL is pure data, so
// there is no compiler freedom to excuse a byte difference — if the recovered
// spec is missing a field or has a flag word wrong, `Rez` output will not match
// the shipped bundle and test/pipl.test.mjs fails.
//
//   node tools/render-pipl.mjs

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import path from "node:path";

const SPECS = path.join(import.meta.dirname, "..", "specs");
const OUT = path.join(import.meta.dirname, "..", "packaging");

// Kinds the AE SDK's AE_General.r understands. 'eFKT' is AEEffect.
const KIND = { eFKT: "AEEffect" };

// The atom order is fixed: it must match the order of the property array in the
// shipped PiPL, because that order is what determines the byte layout.
function render(plugin, p) {
  const num = (v) => {
    if (typeof v === "number") return v;
    const n = Number(v);
    if (!Number.isFinite(n)) throw new Error(`${plugin}: not a number: ${v}`);
    return n >>> 0; // the atoms are unsigned 32-bit
  };
  const hex = (v) => `0x${num(v).toString(16).padStart(8, "0")}`;

  const pipVer = num(p.ePVR);
  const pipMajor = (pipVer >>> 16) & 0xffff;
  const pipMinor = pipVer & 0xffff;

  const kind = KIND[p.kind];
  if (!kind) throw new Error(`${plugin}: unknown PiPL kind ${p.kind}`);

  const missing = ["name", "catg", "mi64", "ma64", "ePVR", "eSVR", "eVER",
                   "eINF", "eGLO", "eGL2", "eMNA", "aeFL"]
    .filter((k) => p[k] === undefined);
  if (missing.length) throw new Error(`${plugin}: spec is missing ${missing.join(", ")}`);

  return `// ${plugin}PiPL.r — PiPL resource for the ${plugin} effect.
//
// GENERATED by tools/render-pipl.mjs from specs/${plugin}.json. Do not edit by
// hand; edit the spec (or the generator) and re-render.
//
// Building requires a local Adobe After Effects SDK. Set AE_SDK_DIR to its
// "Examples" directory, then:
//
//   Rez -useDF -o ${plugin}.rsrc \\
//       -I "$AE_SDK_DIR/Headers" -I "$AE_SDK_DIR/Resources" \\
//       -d AE_OS_MAC -d AE_PROC_ARM64 ${plugin}PiPL.r
//
// Every value below was recovered from the shipped bundle's PIPL resource and
// is asserted against it by test/pipl.test.mjs, which rebuilds this file and
// demands the shipped bytes back.

#include "AEConfig.h"
#include "AE_EffectVers.h"

#ifndef AE_OS_WIN
	#include "AE_General.r"
#endif

resource 'PiPL' (16000) {
	{	/* array properties: 13 elements */
		/* [1] */
		Kind {
			${kind}
		},
		/* [2] */
		Name {
			"${p.name}"
		},
		/* [3] */
		Category {
			"${p.catg}"
		},
#if defined(AE_OS_MAC)
		/* [4] CodeMacIntel64 -> 'mi64' */
		CodeMacIntel64 {"${p.mi64}"},
		/* [5] CodeMacARM64   -> 'ma64' */
		CodeMacARM64 {"${p.ma64}"},
#elif defined(AE_OS_WIN)
	#if defined(AE_PROC_ARM64)
		CodeWinARM64 {"${p.ma64}"},
	#elif defined(AE_PROC_INTELx64)
		CodeWin64X86 {"${p.mi64}"},
	#endif
#endif
		/* [6] */
		AE_PiPL_Version {
			${pipMajor},
			${pipMinor}
		},
		/* [7] */
		AE_Effect_Spec_Version {
			PF_PLUG_IN_VERSION,
			PF_PLUG_IN_SUBVERS
		},
		/* [8] */
		AE_Effect_Version {
			${hex(p.eVER)}
		},
		/* [9] */
		AE_Effect_Info_Flags {
			${hex(p.eINF)}
		},
		/* [10] */
		AE_Effect_Global_OutFlags {
			${hex(p.eGLO)}
		},
		AE_Effect_Global_OutFlags_2 {
			${hex(p.eGL2)}
		},
		/* [11] */
		AE_Effect_Match_Name {
			"${p.eMNA}"
		},
		/* [12] */
		AE_Reserved_Info {
			${hex(p.aeFL)}
		}
	}
};
`;
}

function main() {
  const files = readdirSync(SPECS)
    .filter((f) => f.endsWith(".json") && f !== "index.json")
    .sort();
  if (!files.length) {
    console.error("no specs found — run tools/recover.mjs first");
    return 1;
  }

  mkdirSync(OUT, { recursive: true });
  const written = [];
  for (const f of files) {
    const spec = JSON.parse(readFileSync(path.join(SPECS, f), "utf8"));
    if (!spec.pipl) {
      console.warn(`skipping ${spec.plugin}: no PiPL in its spec`);
      continue;
    }
    writeFileSync(path.join(OUT, `${spec.plugin}PiPL.r`), render(spec.plugin, spec.pipl));
    written.push(spec.plugin);
  }
  console.log(`rendered ${written.length} PiPL sources into packaging/`);
  return 0;
}

process.exitCode = main();
